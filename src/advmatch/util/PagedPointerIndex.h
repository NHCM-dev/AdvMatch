#ifndef ADVMATCH_PAGED_POINTER_INDEX_H
#define ADVMATCH_PAGED_POINTER_INDEX_H

#include <array>
#include <cstddef>
#include <cstdint>
#include <memory>
#include <vector>

namespace advmatch
{
    // Non-owning index for monotonic IDs. Lookup uses two array accesses and
    // never hashes/scans. Erasing the last entry releases that page; only its
    // directory slot remains. Indexed objects must have stable addresses.
    template <typename Value, std::size_t PageBits = 10>
    class PagedPointerIndex
    {
        static_assert(PageBits > 0 && PageBits < 20);
        static constexpr std::size_t PageSize = std::size_t(1) << PageBits;

        struct Page
        {
            std::array<Value*, PageSize> values{};
            std::size_t count = 0;
        };

        std::vector<std::unique_ptr<Page>> pages;

    public:
        void reserve(std::size_t count)
        {
            const std::size_t pageCount = count / PageSize + (count % PageSize != 0);
            if (pageCount > this->pages.size())
            {
                this->pages.resize(pageCount);
            }

            for (std::size_t index = 0; index < pageCount; ++index)
            {
                if (!this->pages[index])
                {
                    this->pages[index] = std::make_unique<Page>();
                }
            }
        }

        Value* get(std::uint64_t id) const noexcept
        {
            if (id == 0)
            {
                return nullptr;
            }

            const auto pageId = (id - 1) >> PageBits;
            if (pageId >= this->pages.size() || !this->pages[pageId])
            {
                return nullptr;
            }

            return this->pages[pageId]->values[(id - 1) & (PageSize - 1)];
        }

        bool insert(std::uint64_t id, Value& value)
        {
            if (id == 0)
            {
                return false;
            }

            // IDs are generated by the owner, starting at one. Reserve/growth
            // is amortized; allocate index pages before a latency-critical run.
            const std::size_t pageId = static_cast<std::size_t>((id - 1) >> PageBits);
            if (pageId >= this->pages.size())
            {
                this->pages.resize(pageId + 1);
            }

            auto& page = this->pages[pageId];
            if (!page)
            {
                page = std::make_unique<Page>();
            }

            Value*& slot = page->values[(id - 1) & (PageSize - 1)];
            if (!slot)
            {
                ++page->count;
            }

            slot = &value;
            return true;
        }

        void erase(std::uint64_t id) noexcept
        {
            if (!this->get(id))
            {
                return;
            }

            auto& page = this->pages[(id - 1) >> PageBits];
            page->values[(id - 1) & (PageSize - 1)] = nullptr;
            if (--page->count == 0)
            {
                page.reset();
            }
        }
    };
}

#endif // ADVMATCH_PAGED_POINTER_INDEX_H
